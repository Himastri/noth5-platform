import re, sys
from pathlib import Path
def compile_noth5_to_py(noth5_path, py_path):
    text = Path(noth5_path).read_text()
    lines = ["# Generated by NOTH5 Compiler Lite V80","import eehim_db_lite",""]
    m = re.search(r'OPEN\s+DB\s+"([^"]+)"', text)
    db = m.group(1) if m else "ACTIVE.db"
    lines.append(f'db = eehim_db_lite.open("{db}")')
    for val,color,label in re.findall(r'SLIDER.*VALUE\s+(\d+).*COLOR\s+"([^"]+)".*LABEL\s+"([^"]+)"', text):
        lines.append(f'render_slider_inside_bubble(value={val}, color="{color}", label="{label}")')
    for val,label in re.findall(r'RATING.*VALUE\s+(\d+).*LABEL\s+"([^"]+)"', text):
        lines.append(f'render_rating_inside_bubble(value={val}, label="{label}")')
    Path(py_path).write_text("\n".join(lines))
    print(f"Compiled {noth5_path} -> {py_path}")
if __name__ == "__main__":
    compile_noth5_to_py(sys.argv[1], sys.argv[2])
